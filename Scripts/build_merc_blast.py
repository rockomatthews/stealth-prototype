"""Derive textured cosmetic fragments from the user's own merc mesh.
No new third party models. Each cut retains the original UVs; closed cut faces
use a separate dark interior material. Runtime fragments have cosmetic physics.
"""
import bpy,bmesh,json,math,random
from pathlib import Path
from mathutils import Vector
P=Path(__file__).resolve().parents[1];OUT=P/'Art/Grab/Blast';OUT.mkdir(parents=True,exist_ok=True)
bpy.ops.wm.open_mainfile(filepath=str(P/'Art/RiggedCharacters/Merc_rigged.blend'))
source=next(o for o in bpy.context.scene.objects if o.type=='MESH')
# Assign each triangle by weighted skinning region, keeping recognizable sleeves,
# gloves, helmet and boots rather than substituting generic primitive cubes.
def region(n):
 if n.startswith(('head','neck')):return 'Head'
 if n.startswith(('upperarm','clavicle')):return 'UpperArmR' if n.endswith('_r') else 'UpperArmL'
 if n.startswith(('lowerarm','hand','index','middle','ring','pinky','thumb')):return 'ForearmR' if n.endswith('_r') else 'ForearmL'
 if n.startswith('thigh'):return 'ThighR' if n.endswith('_r') else 'ThighL'
 if n.startswith(('calf','foot','ball')):return 'BootR' if n.endswith('_r') else 'BootL'
 if n=='pelvis':return 'Hips'
 return 'Torso'
groups={g.index:region(g.name) for g in source.vertex_groups};regions={}
for f in source.data.polygons:
 scores={}
 for vi in f.vertices:
  for g in source.data.vertices[vi].groups:
   k=groups.get(g.group,'Torso');scores[k]=scores.get(k,0)+g.weight
 k=max(scores,key=scores.get) if scores else 'Torso';regions.setdefault(k,[]).append(f.index)
report={}
for name,faces in regions.items():
 if len(faces)<20:continue
 mesh=source.data.copy();obj=bpy.data.objects.new('SM_Merc'+name,mesh);bpy.context.collection.objects.link(obj)
 bm=bmesh.new();bm.from_mesh(mesh);bm.faces.ensure_lookup_table();keep=set(faces)
 bmesh.ops.delete(bm,geom=[f for i,f in enumerate(bm.faces) if i not in keep],context='FACES')
 interior=bpy.data.materials.get('M_CutInterior') or bpy.data.materials.new('M_CutInterior');mesh.materials.append(interior)
 edges=[e for e in bm.edges if e.is_boundary]
 if edges:
  fill=bmesh.ops.holes_fill(bm,edges=edges,sides=0)
  for face in fill.get('faces',[]):face.material_index=1
 bm.to_mesh(mesh);bm.free();mesh.update()
 if not mesh.vertices:continue
 center=sum((v.co for v in mesh.vertices),Vector())/len(mesh.vertices)
 for v in mesh.vertices:v.co-=center
 obj.location=(0,0,0)
 bpy.ops.object.select_all(action='DESELECT');obj.select_set(True);bpy.context.view_layer.objects.active=obj
 bpy.ops.export_scene.fbx(filepath=str(OUT/(obj.name+'.fbx')),use_selection=True,object_types={'MESH'},add_leaf_bones=False,axis_forward='-Y',axis_up='Z')
 report[name]={'center':list(center),'triangles':len(mesh.polygons),'asset':obj.name};obj.hide_set(True)
# Uneven smoke/dust lobes, no glowing opaque sphere. Low-poly physical surfaces
# receive warehouse lighting; the transient impulse light is separate.
bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2,radius=1);o=bpy.context.object;o.name='SM_BlastCloud'
rng=random.Random(811)
for v in o.data.vertices:v.co*=rng.uniform(.78,1.21)
bpy.ops.object.select_all(action='DESELECT');o.select_set(True)
bpy.ops.export_scene.fbx(filepath=str(OUT/'SM_BlastCloud.fbx'),use_selection=True,object_types={'MESH'},axis_forward='-Y',axis_up='Z')
(OUT/'fragments.json').write_text(json.dumps(report,indent=2));print('MERC_BLAST_BUILT',json.dumps(report))

bones={'Head':'head','Torso':'spine_03','Hips':'pelvis','UpperArmR':'upperarm_r','UpperArmL':'upperarm_l','ForearmR':'lowerarm_r','ForearmL':'lowerarm_l','ThighR':'thigh_r','ThighL':'thigh_l','BootR':'calf_r','BootL':'calf_l'}
lines=['    {TEXT("%s"),TEXT("%s"),FVector(%.5ff,%.5ff,%.5ff)},'%(name,bones[name],*report[name]['center']) for name in sorted(report)]
(P/'Source/StealthPrototype/SPBlastParts.inl').write_text('// Generated by Scripts/build_merc_blast.py from the existing merc mesh.\n'+'\n'.join(lines)+'\n')
